#!/usr/bin/env python3
"""Generate the pairwise (all-pairs) configuration table for PairwiseConfigTest.

miniLB has six independent settings that change what happens to a request:

    algorithm   round_robin | least_connections | weighted
    cache       off | on
    redis       down | up
    rate_limit  off | on
    method      GET | HEAD | POST
    backends    all_up | one_down | all_down

Testing every combination needs 3*2*2*2*3*3 = 216 system tests (each starts
real processes). Pairwise testing picks a much smaller set of combinations in
which every *pair* of values of every two settings still occurs together at
least once. Most configuration faults are triggered by one setting or by the
interaction of two, which is what this set is guaranteed to exercise.

The table is built with a simple greedy algorithm: repeatedly add the
combination that covers the most pairs not covered yet (ties are broken by
the order of itertools.product, so the output is deterministic).

Usage:
    python3 software-testing/tools/pairwise.py            # print the table
    python3 software-testing/tools/pairwise.py --write    # regenerate PairwiseCases.inc
"""

import itertools
import pathlib
import sys

FACTORS = [
    ("algorithm", ["round_robin", "least_connections", "weighted"]),
    ("cache", ["off", "on"]),
    ("redis", ["down", "up"]),
    ("rate_limit", ["off", "on"]),
    ("method", ["GET", "HEAD", "POST"]),
    ("backends", ["all_up", "one_down", "all_down"]),
]


def pairs_of(row):
    """All (factor index, value, factor index, value) pairs in one combination."""
    return {(i, row[i], j, row[j]) for i in range(len(row)) for j in range(i + 1, len(row))}


def all_pairs():
    wanted = set()
    for i, (_, values_i) in enumerate(FACTORS):
        for j in range(i + 1, len(FACTORS)):
            for a in values_i:
                for b in FACTORS[j][1]:
                    wanted.add((i, a, j, b))
    return wanted


def generate():
    candidates = list(itertools.product(*(values for _, values in FACTORS)))
    uncovered = all_pairs()
    table = []
    while uncovered:
        best = max(candidates, key=lambda row: len(pairs_of(row) & uncovered))
        table.append(best)
        uncovered -= pairs_of(best)
    return table


def check(table):
    """Independent check of the result: every pair must occur in some row."""
    missing = all_pairs()
    for row in table:
        missing -= pairs_of(row)
    assert not missing, f"pairs not covered: {sorted(missing)}"


def render(table):
    lines = [
        "// GENERATED by software-testing/tools/pairwise.py --write. Do not edit by hand.",
        f"// {len(table)} of {len(list(itertools.product(*(v for _, v in FACTORS))))} combinations;"
        f" every pair of values occurs at least once ({len(all_pairs())} pairs).",
        "//   " + ", ".join(name for name, _ in FACTORS),
    ]
    for row in table:
        lines.append("    {" + ", ".join(f'"{value}"' for value in row) + "},")
    return "\n".join(lines) + "\n"


def main():
    table = generate()
    check(table)
    text = render(table)
    if "--write" in sys.argv:
        target = pathlib.Path(__file__).resolve().parent.parent / "tests" / "integration" / "PairwiseCases.inc"
        target.write_text(text)
        print(f"wrote {len(table)} cases to {target}")
    else:
        print(text, end="")


if __name__ == "__main__":
    main()
