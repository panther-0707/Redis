#pragma once

#include "miniLB/balancer/BackendPool.hpp"

#include <atomic>
#include <cstdint>
#include <string>

namespace minilb {

// Live counters, exposed as JSON by GET /stats.
//
// Thread-safety: every counter is a std::atomic, so any thread can update
// them without a lock. /stats reads them one by one, so the numbers in one
// report can be a few requests apart from each other. For monitoring that
// is fine, and it keeps the request path lock-free.
struct Metrics {
    std::atomic<std::uint64_t> totalRequests{0};   // requests answered (excluding /stats)
    std::atomic<std::uint64_t> cacheHits{0};
    std::atomic<std::uint64_t> cacheMisses{0};
    std::atomic<std::uint64_t> rateLimited{0};     // 429 responses
    std::atomic<std::uint64_t> errors{0};          // error responses generated by miniLB
                                                   // itself (400-class, 502, 503, 504)
    std::atomic<int> activeConnections{0};         // client connections currently open

    // Renders the counters plus per-backend state as a JSON document.
    std::string toJson(const BackendPool& pool, const std::string& algorithm,
                       bool redisAvailable) const;
};

} // namespace minilb
